#!/usr/bin/env python3
"""A Torznab indexer that serves one pre-built torrent, for the grab test.

The e2e can prove that qBittorrent, Sonarr, Radarr and Prowlarr are *wired*; only a
grab proves the stack *works*. That needs an indexer, and a real one needs credentials
nobody wants in a public repo, so this serves the smallest honest version: a caps
document, a search that returns one release, and the torrent the test built.

The torrent is read from a mounted directory (hack/make-torrent.py wrote it), so the
bytes this indexer advertises are exactly the bytes the test places under qBittorrent's
save path. The media itself is a five-second test pattern generated by ffmpeg: no third
party's content is involved anywhere in this test.

Usage: mock-indexer.py [--port 8080] [--host 0.0.0.0]
"""
import argparse
import json
import os
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse
from xml.sax.saxutils import escape

TORRENT_DIR = os.environ.get("S5N_TORRENT_DIR", "/torrent")
with open(os.path.join(TORRENT_DIR, "meta.json"), encoding="utf-8") as fh:
    META = json.load(fh)
with open(os.path.join(TORRENT_DIR, "torrent.bin"), "rb") as fh:
    TORRENT = fh.read()

RELEASE_NAME = META["name"]
SIZE = META["size"]
INFOHASH = META["infohash"]


def caps_xml():
    return """<?xml version="1.0" encoding="UTF-8"?>
<caps>
  <server version="1.0" title="s5n mock indexer"/>
  <limits max="100" default="100"/>
  <searching>
    <search available="yes" supportedParams="q"/>
    <tv-search available="yes" supportedParams="q,season,ep"/>
    <movie-search available="yes" supportedParams="q"/>
  </searching>
  <categories>
    <category id="2000" name="Movies">
      <subcat id="2030" name="Movies/SD"/>
      <subcat id="2040" name="Movies/HD"/>
    </category>
    <category id="5000" name="TV">
      <subcat id="5030" name="TV/SD"/>
      <subcat id="5040" name="TV/HD"/>
    </category>
  </categories>
</caps>
"""


def search_xml(base_url, category):
    link = f"{base_url}/download/{RELEASE_NAME}.torrent"
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:torznab="http://torznab.com/schemas/2015/feed">
  <channel>
    <title>s5n mock indexer</title>
    <item>
      <title>{escape(RELEASE_NAME)}</title>
      <guid isPermaLink="false">s5n-mock-1</guid>
      <link>{escape(link)}</link>
      <enclosure url="{escape(link)}" length="{SIZE}" type="application/x-bittorrent"/>
      <pubDate>Mon, 02 Nov 2026 00:00:00 +0000</pubDate>
      <size>{SIZE}</size>
      <torznab:attr name="category" value="{category}"/>
      <torznab:attr name="size" value="{SIZE}"/>
      <torznab:attr name="seeders" value="10"/>
      <torznab:attr name="peers" value="10"/>
      <torznab:attr name="infohash" value="{INFOHASH}"/>
      <torznab:attr name="downloadvolumefactor" value="0"/>
      <torznab:attr name="uploadvolumefactor" value="1"/>
    </item>
  </channel>
</rss>
"""


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, format, *args):  # noqa: A002 - override signature
        print(f"{self.address_string()} {format % args}", flush=True)

    def _send(self, status, body, ctype):
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        url = urlparse(self.path)
        query = parse_qs(url.query)
        base = f"http://{self.headers.get('Host', self.server.server_address[0])}"

        if url.path == "/api":
            kind = query.get("t", [""])[0]
            if kind == "caps":
                self._send(200, caps_xml().encode(), "application/xml")
                return
            if kind in ("search", "tvsearch", "tv-search"):
                self._send(200, search_xml(base, 5040).encode(), "application/xml")
                return
            if kind in ("movie", "moviesearch", "movie-search"):
                self._send(200, search_xml(base, 2040).encode(), "application/xml")
                return
            self._send(400, b"unsupported t=", "text/plain")
            return

        if url.path.startswith("/download/"):
            self._send(200, TORRENT, "application/x-bittorrent")
            return

        if url.path == "/healthz":
            self._send(200, b'{"ok":true}', "application/json")
            return

        self._send(404, b"not found", "text/plain")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8080)
    ap.add_argument("--host", default="0.0.0.0")
    args = ap.parse_args()
    server = ThreadingHTTPServer((args.host, args.port), Handler)
    print(json.dumps(META), flush=True)
    server.serve_forever()


if __name__ == "__main__":
    main()
